#!/usr/bin/env node
/**
 * Create a local Play upload keystore + android/keystore.properties.
 * Files are gitignored. Back them up — Google cannot reset an upload key easily.
 */
import { randomBytes } from 'node:crypto';
import { existsSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { spawnSync } from 'node:child_process';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const androidDir = join(root, 'android');
const storeFileName = 'upload-keystore.jks';
const storePath = join(androidDir, storeFileName);
const propsPath = join(androidDir, 'keystore.properties');

if (existsSync(storePath) || existsSync(propsPath)) {
  console.error('Upload key already exists. Refusing to overwrite.');
  console.error(`  ${storePath}`);
  console.error(`  ${propsPath}`);
  process.exit(1);
}

function findKeytool() {
  const exe = process.platform === 'win32' ? 'keytool.exe' : 'keytool';
  const candidates = [];
  if (process.env.JAVA_HOME) {
    candidates.push(join(process.env.JAVA_HOME, 'bin', exe));
  }
  candidates.push(
    join('C:\\Program Files\\Android\\Android Studio\\jbr\\bin', exe),
    join('C:\\Program Files\\Java\\jdk-17\\bin', exe),
    join('C:\\Program Files\\Java\\jdk-21\\bin', exe),
    exe,
  );
  for (const bin of candidates) {
    const probe = spawnSync(bin, ['-help'], { encoding: 'utf8' });
    if (probe.error) continue;
    if (probe.status === 0 || probe.status === 1) return bin;
  }
  return null;
}

const keytool = findKeytool();
if (!keytool) {
  console.error('keytool not found. Install a JDK or Android Studio, then retry.');
  process.exit(1);
}

const password = randomBytes(24).toString('base64url');
const args = [
  '-genkeypair',
  '-v',
  '-storetype',
  'PKCS12',
  '-keystore',
  storePath,
  '-alias',
  'upload',
  '-keyalg',
  'RSA',
  '-keysize',
  '2048',
  '-validity',
  '10000',
  '-storepass',
  password,
  '-keypass',
  password,
  '-dname',
  'CN=IvPlayer Upload, OU=IvPlayer, O=Mehmet Burak Firat, L=Ivrindi, ST=Balikesir, C=TR',
];

const result = spawnSync(keytool, args, { stdio: 'inherit' });
if (result.status !== 0) {
  process.exit(result.status ?? 1);
}

const props = [
  '# Generated by scripts/create-android-upload-key.mjs — do not commit.',
  `storeFile=${storeFileName}`,
  `storePassword=${password}`,
  'keyAlias=upload',
  `keyPassword=${password}`,
  '',
].join('\n');

writeFileSync(propsPath, props, { encoding: 'utf8', mode: 0o600 });
console.log('Created android/upload-keystore.jks and android/keystore.properties');
console.log('Back these two files up offline. Do not commit them. Do not put the APK/AAB on the public site.');
